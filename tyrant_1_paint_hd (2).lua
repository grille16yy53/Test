				if t - 1 ~= m then qq[t] = c[ii] ii = ii + 1 end
			end
			qq[m + 1] = math.sqrt(math.max(0, 1 - (c[1] ^ 2 + c[2] ^ 2 + c[3] ^ 2)))
			local mag = math.sqrt(qq[1] ^ 2 + qq[2] ^ 2 + qq[3] ^ 2 + qq[4] ^ 2)
			local cn = rd(4)
			RAW[#RAW + 1] = {
				bone = name, cf = CFn(x * SCALE, y * SCALE, z * SCALE, qq[1] / mag, qq[2] / mag, qq[3] / mag, qq[4] / mag),
				size = V3(math.clamp(sx * SCALE, 0.1, 2.5), math.clamp(sy * SCALE, 0.1, 2.5), math.clamp(sz * SCALE, 0.1, 2.5)),
				col = { math.floor(cn / 65536), math.floor(cn / 256) % 256, cn % 256 },
			}
		end
	end
end
buildFigure()

local function r2(v) return math.max(0.1, math.floor(v * 100 + 0.5) / 100) end
local BOXES = {}
for _, b in ipairs(RAW) do
	BOXES[#BOXES + 1] = { bone = b.bone, col = b.col, cf = b.cf, size = V3(r2(b.size.X), r2(b.size.Y), r2(b.size.Z)) }
end
if #BOXES > MAX_PARTS then warn(("[Tyrant] %d plates but cap is %d"):format(#BOXES, MAX_PARTS)) end

local function gridOf(studs) return math.clamp(studs / 2.5, 0.04, 1) end
local function q(v) return math.floor(v * 100 + 0.5) end
local function c255(c)
	return math.floor(c.R * 255 + 0.5), math.floor(c.G * 255 + 0.5), math.floor(c.B * 255 + 0.5)
end
local function makeKey(gx, gy, gz, r, g, b)
	return q(gx) .. "," .. q(gy) .. "," .. q(gz) .. "|" .. r .. "," .. g .. "," .. b
end
for _, b in ipairs(BOXES) do
	b.gx, b.gy, b.gz = gridOf(b.size.X), gridOf(b.size.Y), gridOf(b.size.Z)
	b.r, b.g, b.b = b.col[1], b.col[2], b.col[3]
	b.color = Color3.fromRGB(b.r, b.g, b.b)
	b.key = makeKey(b.gx, b.gy, b.gz, b.r, b.g, b.b)
end
