lbl.Parent = gui

local function key(k) return UIS:IsKeyDown(k) and not UIS:GetFocusedTextBox() end
local function angDiff(a, b) return (a - b + math.pi) % (2 * math.pi) - math.pi end
local conn, frame, time0 = nil, 0, 0
local mouse = lp:GetMouse()

local function stop()
	if conn then conn:Disconnect() end
	pcall(function() controls:Enable() end)
	if hum and oldWS then pcall(function() hum.WalkSpeed = oldWS end) end
	cam.CameraType = oldCamType
	gui:Destroy()
	getgenv().ScarabWalking = false
	print("[Scarab] stopped")
end

local cfs = table.create(#parts)
conn = RunService.Heartbeat:Connect(function(dt)
	dt = math.min(dt, 1 / 20)
	time0 = time0 + dt
	frame = frame + 1
	if key(Enum.KeyCode.P) then return stop() end
	-- input -----------------------------------------------------------------
	local thr = (key(Enum.KeyCode.W) and 1 or 0) - (key(Enum.KeyCode.S) and 1 or 0)
	local st = (key(Enum.KeyCode.A) and 1 or 0) - (key(Enum.KeyCode.D) and 1 or 0)
	local run = key(Enum.KeyCode.LeftShift)
	stance = math.clamp(stance + ((key(Enum.KeyCode.R) and 1 or 0) - (key(Enum.KeyCode.F) and 1 or 0)) * 4 * dt, -3, 4)
	camOrbit = camOrbit + ((key(Enum.KeyCode.E) and 1 or 0) - (key(Enum.KeyCode.Q) and 1 or 0)) * 1.6 * dt
	camZoom = math.clamp(camZoom + ((key(Enum.KeyCode.X) and 1 or 0) - (key(Enum.KeyCode.Z) and 1 or 0)) * 0.8 * dt, 0.4, 2.5)

	yaw = yaw + st * TURN_SPEED * (run and 1.3 or 1) * dt
	local heading = V3(-math.sin(yaw), 0, -math.cos(yaw))
	local speed = (run and RUN_SPEED or WALK_SPEED) * (thr < 0 and 0.6 or 1)
	vel = vel:Lerp(heading * thr * speed, 1 - math.exp(-dt * 4))
	pos = pos + V3(vel.X, 0, vel.Z) * dt

	-- foot placement ---------------------------------------------------------
	local planarSpeed = vel.Magnitude
	local anySwing = { A = false, B = false }
	for _, L in ipairs(LEGS) do if L.swing then anySwing[L.grp] = true end end
	for _, L in ipairs(LEGS) do
		local hw = bodyCF:PointToWorldSpace(L.home)
		if L.swing then
			L.t = L.t + dt / L.dur
			local t = math.min(L.t, 1)
			local e = t * t * (3 - 2 * t)
			local p = L.from:Lerp(L.to, e)
			L.foot = p + V3(0, math.sin(math.pi * t) * STEP_HEIGHT, 0)
			if L.t >= 1 then
				L.swing = false
				L.foot = groundAt(L.to, L.to.Y)
				anySwing[L.grp] = false
			end
		else
			local off = V3(L.foot.X - hw.X, 0, L.foot.Z - hw.Z)
			local other = (L.grp == "A") and "B" or "A"
			local need = off.Magnitude
			if (need > STEP_DIST and not anySwing[other]) or need > STEP_DIST * 1.9 then
				local lead = V3(vel.X, 0, vel.Z) * 0.22
				if planarSpeed < 0.5 then lead = Vector3.zero end
				local target = groundAt(hw + lead + heading * (planarSpeed > 0.5 and STEP_DIST * 0.6 * (thr >= 0 and 1 or -1) or 0), L.foot.Y)
				L.from, L.to = L.foot, target
				L.dur = math.clamp(0.5 * STEP_DIST * 2 / math.max(planarSpeed, 4), 0.2, 0.45)
				L.swing, L.t = true, 0
				anySwing[L.grp] = true
			end
		end
	end

	-- body pose: plane through the four feet -------------------------------------
	local f = { LEGS[1].foot, LEGS[2].foot, LEGS[3].foot, LEGS[4].foot }
	local fg = {}
	for i, L in ipairs(LEGS) do
		fg[i] = L.swing and L.from:Lerp(L.to, math.min(L.t, 1)) or L.foot
	end
	local cen = (fg[1] + fg[2] + fg[3] + fg[4]) / 4
	local nrm = (fg[1] - fg[4]):Cross(fg[2] - fg[3])
	if nrm.Magnitude < 1e-3 then nrm = V3(0, 1, 0) end
	nrm = nrm.Unit
	if nrm.Y < 0 then nrm = -nrm end
	local tilt = math.acos(math.clamp(nrm.Y, -1, 1))
	if tilt > MAX_TILT then nrm = V3(0, 1, 0):Lerp(nrm, MAX_TILT / tilt).Unit end
	upS = upS:Lerp(nrm, 1 - math.exp(-dt * 6)).Unit
	local planeY = cen.Y - (upS.X * (pos.X - cen.X) + upS.Z * (pos.Z - cen.Z)) / upS.Y
	local bob = math.sin(time0 * 7) * 0.12 * math.min(planarSpeed / WALK_SPEED, 1.5)
	local origin = V3(pos.X, planeY, pos.Z) + upS * (stance + bob)
	local look = (heading - upS * heading:Dot(upS)).Unit
	local right = look:Cross(upS).Unit
	bodyCF = CFrame.fromMatrix(origin, right, upS)
	-- the body follows the feet vertically, but keep xz on the commanded path
	pos = V3(pos.X, origin.Y, pos.Z)

	-- turret aims at the mouse ----------------------------------------------------
	local aim = mouse.Hit.Position
	local tl = bodyCF:PointToObjectSpace(aim) - JOINTS.turret
	local wantYaw = math.atan2(-tl.X, -tl.Z)
	local dy = angDiff(wantYaw, turretYaw)
	turretYaw = turretYaw + math.clamp(dy, -2.4 * dt, 2.4 * dt)
	local wantPitch = math.clamp(math.atan2(tl.Y, math.sqrt(tl.X * tl.X + tl.Z * tl.Z)), math.rad(-5), math.rad(50))
	turretPitch = turretPitch + math.clamp(wantPitch - turretPitch, -1.5 * dt, 1.5 * dt)

	-- write plate CFrames -------------------------------------------------------
	for _, i in ipairs(bodyList) do cfs[i] = bodyCF * plates[i].cf end
	local Myaw = CFn(JOINTS.turret) * CFrame.Angles(0, turretYaw, 0) * CFn(-JOINTS.turret)
	local MyawW = bodyCF * Myaw
	for _, i in ipairs(turretList) do cfs[i] = MyawW * plates[i].cf end
	local MbarW = MyawW * CFn(JOINTS.barrel) * CFrame.Angles(turretPitch, 0, 0) * CFn(-JOINTS.barrel)
	for _, i in ipairs(barrelList) do cfs[i] = MbarW * plates[i].cf end
	for li, L in ipairs(LEGS) do
		local At = bodyCF:PointToObjectSpace(L.foot) + (L.j.A - L.j.C)
		local K, A, RU, RS = solveLeg(L, At)
		local MU = bodyCF * CFn(L.j.H) * RU
		for _, e in ipairs(L.U) do cfs[e.i] = MU * e.rel end
		local MS = bodyCF * CFn(K) * RS
		for _, e in ipairs(L.S) do cfs[e.i] = MS * e.rel end
		local MF = bodyCF * CFn(A)
		for _, e in ipairs(L.F) do cfs[e.i] = MF * e.rel end
	end
	local ok = pcall(function() workspace:BulkMoveTo(parts, cfs, Enum.BulkMoveMode.FireCFrameChanged) end)
	if not ok then
		for i, p in ipairs(parts) do pcall(function() p.CFrame = cfs[i] end) end
	end
	-- kill physics drift on a rolling subset of parts
	local s0 = (frame % 4) + 1
	for i = s0, #parts, 4 do
		local p = parts[i]
		p.AssemblyLinearVelocity = Vector3.zero
		p.AssemblyAngularVelocity = Vector3.zero
	end

	-- camera --------------------------------------------------------------------
	if key(Enum.KeyCode.C) and not getgenv().ScarabCamLatch then
		getgenv().ScarabCamLatch = true
		camOn = not camOn
		if not camOn then cam.CameraType = oldCamType end
	elseif not key(Enum.KeyCode.C) then
		getgenv().ScarabCamLatch = false
	end
	if camOn then
		cam.CameraType = Enum.CameraType.Scriptable
		local focus = bodyCF.Position + V3(0, 8, 0)
		local a = yaw + camOrbit
		local off = V3(math.sin(a), 0, math.cos(a)) * CAM_DIST * camZoom + V3(0, CAM_HEIGHT * camZoom, 0)
		local target = CFrame.lookAt(focus + off, focus)
		cam.CFrame = cam.CFrame:Lerp(target, 1 - math.exp(-dt * 6))
	end
end)
print("[Scarab] walking - W/S A/D, Shift run, P to stop")
