	local poleb = ((j.K - j.H) - dirb * (j.K - j.H):Dot(dirb)).Unit
	local nB = dirb:Cross(poleb).Unit
	LEGS[li] = {
		name = name, j = j, grp = GROUP_OF[name],
		LU = (j.K - j.H).Magnitude, LS = (j.A - j.K).Magnitude,
		poleb = poleb,
