local rp = RaycastParams.new()
rp.FilterType = Enum.RaycastFilterType.Exclude
rp.FilterDescendantsInstances = ignore
rp.IgnoreWater = true
local function groundAt(p, fy)
	local r = workspace:Raycast(V3(p.X, p.Y + RAY_UP, p.Z), V3(0, -(RAY_UP + RAY_DOWN), 0), rp)
	if r then return r.Position end
	return V3(p.X, fy, p.Z)
end

local sum, n0 = Vector3.zero, 0
for _, p in ipairs(parts) do sum = sum + p.Position n0 = n0 + 1 end
local centre = sum / math.max(1, n0)
local startGround = groundAt(centre, centre.Y)
local camLook = cam.CFrame.LookVector
local yaw = math.atan2(-camLook.X, -camLook.Z)
local pos = V3(centre.X, startGround.Y, centre.Z)
local upS = V3(0, 1, 0)
local vel = Vector3.zero
local stance, turretYaw, turretPitch = 0, 0, 0
local camOrbit, camZoom, camOn = 0, 1, FOLLOW_CAMERA
local bodyCF = CFrame.new(pos) * CFrame.Angles(0, yaw, 0)
for _, L in ipairs(LEGS) do
	local hw = bodyCF:PointToWorldSpace(L.home)
	L.foot = groundAt(hw, pos.Y)
end

local controls
pcall(function() controls = require(lp.PlayerScripts:WaitForChild("PlayerModule", 2)):GetControls() controls:Disable() end)
local hum = lp.Character and lp.Character:FindFirstChildOfClass("Humanoid")
local oldWS = hum and hum.WalkSpeed
if hum then pcall(function() hum.WalkSpeed = 0 end) end
local oldCamType = cam.CameraType

local gui = Instance.new("ScreenGui")
gui.Name = "ScarabHUD" gui.ResetOnSpawn = false
pcall(function() gui.Parent = (gethui and gethui()) or lp:WaitForChild("PlayerGui") end)
local lbl = Instance.new("TextLabel")
lbl.Size = UDim2.new(0, 460, 0, 40) lbl.Position = UDim2.new(0.5, -230, 1, -60)
