	end
end

-- 2-bone IK in body space: returns knee position, hip rotation, shin rotation, clamped ankle
local function solveLeg(L, At)
	local H = L.j.H
	local v = At - H
	local d = v.Magnitude
	local dmax, dmin = (L.LU + L.LS) * 0.995, math.abs(L.LU - L.LS) + 0.05
	d = math.clamp(d, dmin, dmax)
	local dir = (v.Magnitude > 1e-4) and v.Unit or V3(0, -1, 0)
	local a = math.clamp((L.LU * L.LU + d * d - L.LS * L.LS) / (2 * L.LU * d), -1, 1)
	local sinA = math.sqrt(1 - a * a)
	local pole = L.poleb - dir * L.poleb:Dot(dir)
	if pole.Magnitude < 1e-3 then pole = V3(0, 1, 0) - dir * dir.Y end
	pole = pole.Unit
	local K = H + dir * (L.LU * a) + pole * (L.LU * sinA)
	local A = H + dir * d
	local n = dir:Cross(pole).Unit
	local FU = CFrame.fromMatrix(Vector3.zero, (K - H).Unit, n)
	local FS = CFrame.fromMatrix(Vector3.zero, (A - K).Unit, n)
	return K, A, FU * L.FbU:Inverse(), FS * L.FbS:Inverse()
end

