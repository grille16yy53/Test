	if md.Magnitude > 0.1 then return md end
	local cam = Workspace.CurrentCamera.CFrame
	local f = V(cam.LookVector.X, 0, cam.LookVector.Z)
	local r = V(cam.RightVector.X, 0, cam.RightVector.Z)
	if f.Magnitude < 0.01 then return ZERO end
	f, r = f.Unit, r.Unit
	local d = ZERO
	if UIS:IsKeyDown(Enum.KeyCode.W) then d = d + f end
	if UIS:IsKeyDown(Enum.KeyCode.S) then d = d - f end
	if UIS:IsKeyDown(Enum.KeyCode.D) then d = d + r end
	if UIS:IsKeyDown(Enum.KeyCode.A) then d = d - r end
	return d.Magnitude > 0.1 and d.Unit or ZERO
end

