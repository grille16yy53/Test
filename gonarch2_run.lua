	elseif k == Enum.KeyCode.P then shutdown("P pressed")
	end
end))

----------------------------------------------------------------------
-- LEG STEPPING (diagonal pairs, planted feet do not slide)
----------------------------------------------------------------------
local function updateLegs(dt, R0, moving, hvec)
	local STEP_T = charging and 0.16 or 0.26
	local thr = moving and (charging and 6.5 or 5) or 2
	local busy = { false, false }
	for _, lg in ipairs(legs) do
		lg.home = R0:PointToWorldSpace(lg.foot)
		if lg.stepping then busy[lg.group] = true end
	end
	for _, lg in ipairs(legs) do
		local o = ovr[lg.n]
		if o then
			lg.cur = lg.cur:Lerp(o.pos, 1 - math.exp(-dt * o.k))
			lg.planted, lg.stepping, lg.wasOvr = lg.cur, false, true
		else
			if lg.wasOvr then lg.wasOvr = false lg.planted = lg.cur end
			if not grounded then
				lg.stepping = false
				lg.planted = lg.home
				lg.cur = lg.home + V(0, 2.5, 0)
			elseif lg.stepping then
				lg.t = lg.t + dt / STEP_T
				if lg.t >= 1 then
					lg.stepping, lg.planted, lg.cur = false, lg.to, lg.to
				else
					local e = lg.t * lg.t * (3 - 2 * lg.t)
					lg.cur = lg.from:Lerp(lg.to, e) + V(0, LIFT * math.sin(math.pi * lg.t), 0)
				end
			else
				lg.cur = lg.planted
				if (lg.home - lg.planted).Magnitude > thr and not busy[3 - lg.group] then
					local to = lg.home + V(hvec.X, 0, hvec.Z) * STEP_T * 0.9
					local gy = groundAt(to, pos.Y)
					lg.to = V(to.X, gy + lg.foot.Y, to.Z)
					lg.from, lg.t, lg.stepping = lg.planted, 0, true
					busy[lg.group] = true
				end
			end
		end
	end
end

----------------------------------------------------------------------
-- MAIN LOOP
----------------------------------------------------------------------
local W, lastW = {}, {}
local bulkParts, bulkCFs, lastN = {}, {}, 0
local moveAcc, fastCam, hideT = 0, 0, 0

local function pruneDead()
	local keep, keepBy = {}, {}
	for _, f in ipairs(followers) do
		if f.part.Parent then
			keep[#keep + 1] = f
			if byBone[f.bone] and byBone[f.bone][1] == f then keepBy[f.bone] = { f } end
		end
	end
	followers = keep
	byBone = keepBy
	return #keep
end

local function frame(dt)
	dt = math.min(dt, 0.1)
	local now = os.clock()

	-- movement
	local md = moveDir()
	local hvec = ZERO
	if not ATTACK and md.Magnitude > 0.1 then
		hvec = md * CFG.WALK_SPEED * (charging and CFG.CHARGE_MUL or 1)
		local target = math.atan2(-md.X, -md.Z)
		local d = (target - yaw + math.pi) % (2 * math.pi) - math.pi
		yaw = yaw + d * math.min(1, dt * (charging and 3 or 5))
	end
	pos = pos + hvec * dt
	hv = hvec.Magnitude

	vy = vy - Workspace.Gravity * dt
	local newY = pos.Y + vy * dt
	local top = math.max(pos.Y, newY) + 10
	local res = Workspace:Raycast(V(pos.X, top, pos.Z), V(0, (math.min(pos.Y, newY) - 3) - top, 0), rayParams)
	local wasG = grounded
	grounded = false
	if res then
		local gy = res.Position.Y
		if newY <= gy + 0.05 or (wasG and vy <= 0 and pos.Y - gy < 6) then
			newY, vy, grounded = gy, 0, true
		end
	end
	pos = V(pos.X, newY, pos.Z)
	if grounded then lastSafe = pos end
	if pos.Y < Workspace.FallenPartsDestroyHeight + 200 then pos, vy = lastSafe + V(0, 5, 0), 0 end

	-- pose smoothing
	local alpha = 1 - math.exp(-dt * 8)
	for k, v in pairs(TGT) do P[k] = P[k] + (v - P[k]) * alpha end
	local sh = P.shake
	local bob = math.sin(now * 1.5) * 0.22 + ((hv > 1) and math.sin(now * (charging and 16 or 9)) * 0.3 or 0)
	local lean = -0.07 * math.min(hv / CFG.WALK_SPEED, 2.2)
	local hx = P.headX + (charging and -0.3 or 0) + math.sin(now * 0.9) * 0.03
	local hy = P.headY + math.sin(now * 47) * 0.04 * sh
	local hz = P.headZ + math.sin(now * 53) * 0.04 * sh

	-- body
	local R0 = CF(pos) * ANGLES(0, yaw, 0)
	local Tb = R0 * CF(0, bob + P.drop + math.sin(now * 61) * 0.12 * sh, 0)
		* rotAbout(BODYC, ANGLES(P.bodyX + lean, 0, P.bodyZ + math.sin(now * 1.1) * 0.01))
	W.root = Tb * BIND.root
	W.top = Tb * rotAbout(BIND.top.Position, ANGLES(hx, hy, hz)) * BIND.top

	-- sack: chain with lazy sway
	for i, n in ipairs(SACKS) do
		local ang = ANGLES(
			0.09 * math.sin(now * 1.6 - i * 0.8) + 0.05 * sh * math.sin(now * 40 + i),
			0,
			0.07 * math.sin(now * 1.25 - i * 0.9 + 1))
		W[n] = W[SACK_PARENT[n]] * SACK_LOCAL[n] * ang
	end

	-- legs
	updateLegs(dt, R0, hv > 1, hvec)
	for _, lg in ipairs(legs) do
		local n = lg.n
		W[n .. "1"] = Tb * BIND[n .. "1"]
		local P2 = Tb:PointToWorldSpace(lg.p2)
		local d = lg.cur - P2
		local dist = math.clamp(d.Magnitude, math.abs(lg.a - lg.b) + 0.05, lg.a + lg.b - 0.05)
		local u = (d.Magnitude > 1e-4) and d.Unit or V(0, -1, 0)
		local x = (lg.a * lg.a + dist * dist - lg.b * lg.b) / (2 * dist)
		local h = math.sqrt(math.max(lg.a * lg.a - x * x, 0))
		local pole = Tb:VectorToWorldSpace(lg.poleB)
		pole = pole - u * pole:Dot(u)
		pole = (pole.Magnitude > 1e-3) and pole.Unit or V(0, 1, 0)
		local K = P2 + u * x + pole * h
		local Fp = P2 + u * dist
		W[n .. "2"] = CF(P2) * swing(Tb:VectorToWorldSpace(lg.dir2), (K - P2).Unit) * rotOnly(Tb * BIND[n .. "2"])
		W[n .. "3"] = CF(K) * swing(Tb:VectorToWorldSpace(lg.dir3), (Fp - K).Unit) * rotOnly(Tb * BIND[n .. "3"])
	end

	-- move parts at UPDATE_HZ (driver part of every bone; the rest is welded to it)
	moveAcc = moveAcc + dt
	if moveAcc >= 1 / CFG.UPDATE_HZ then
		moveAcc = 0
		local n = 0
		for _, row in ipairs(BONE_DEF) do
			local bn = row[1]
			local list = byBone[bn]
			if list then
				local Wb, Pb = W[bn], lastW[bn]
				lastW[bn] = Wb
				local still = Pb and (Wb.Position - Pb.Position).Magnitude < 0.002
					and Wb.LookVector:Dot(Pb.LookVector) > 0.999995
					and Wb.RightVector:Dot(Pb.RightVector) > 0.999995
				if not still then
					for i = 1, #list do
						local f = list[i]
						local cf = Wb * f.cf
						n = n + 1
						bulkParts[n], bulkCFs[n] = f.part, cf
						f.bp.Position = cf.Position
						f.bg.CFrame = cf
					end
				end
			end
		end
		for i = n + 1, lastN do bulkParts[i], bulkCFs[i] = nil, nil end
		lastN = n
		if n > 0 then
			local ok = pcall(Workspace.BulkMoveTo, Workspace, bulkParts, bulkCFs, Enum.BulkMoveMode.FireCFrameChanged)
			if not ok then
				local left = pruneDead()
				lastN = 0
				if left < count * 0.5 then shutdown("the plane was despawned") return end
			end
		end
	end

	-- camera target + keep the real character hidden INSIDE the body
	camPart.CFrame = CF(pos + V(0, 10, 0))
	RealRoot.Anchored = true
	RealRoot.CFrame = W.root
	RealRoot.AssemblyLinearVelocity = ZERO
	hideT = hideT + dt
	if hideT > 0.25 then
		hideT = 0
		for _, d in ipairs(Character:GetDescendants()) do
			if d:IsA("BasePart") then
				d.CanCollide = false
				if CFG.HIDE_SELF then d.LocalTransparencyModifier = 1 end
			end
		end
	end
	fastCam = fastCam + dt
	if fastCam > 1 then
		fastCam = 0
		rayParams.FilterDescendantsInstances = listExclude()
		local cam = Workspace.CurrentCamera
		if cam.CameraSubject ~= camPart then cam.CameraSubject = camPart end
	end
end

local errCount = 0
track(RunService.Heartbeat:Connect(function(dt)
	if not alive then return end
	local ok, err = pcall(frame, dt)
	if ok then errCount = 0
	else
		errCount = errCount + 1
		if errCount == 1 then warn("[Gonarch] frame error: " .. tostring(err)) end
		if errCount > 90 then shutdown("too many errors: " .. tostring(err)) end
	end
end))

