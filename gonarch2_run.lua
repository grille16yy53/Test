local function groundAt(p, fallback)
	local res = Workspace:Raycast(V(p.X, p.Y + 14, p.Z), V(0, -80, 0), rayParams)
	return res and res.Position.Y or fallback
end
local function fwdVec() return V(-math.sin(yaw), 0, -math.cos(yaw)) end
local function faceCamera()
	local lv = Workspace.CurrentCamera.CFrame.LookVector
	if V(lv.X, 0, lv.Z).Magnitude > 0.01 then yaw = math.atan2(-lv.X, -lv.Z) end
end
do
	local R0 = CF(pos) * ANGLES(0, yaw, 0)
	for _, lg in ipairs(legs) do
		lg.planted = R0:PointToWorldSpace(lg.foot)
		lg.cur = lg.planted
		lg.home = lg.planted
	end
end

----------------------------------------------------------------------
-- POSE TARGETS (radians / studs) + ATTACKS
----------------------------------------------------------------------
local P = { headX = 0, headY = 0, headZ = 0, bodyX = 0, bodyZ = 0, drop = 0, shake = 0 }
local TGT = { headX = 0, headY = 0, headZ = 0, bodyX = 0, bodyZ = 0, drop = 0, shake = 0 }
local ovr = {} -- leg name -> { pos = Vector3, k = follow speed }
local function setT(t) for k, v in pairs(t) do TGT[k] = v end end
local function resetTargets() for k in pairs(TGT) do TGT[k] = 0 end end

local function runAttack(fn)
	if ATTACK then return end
	ATTACK = true
	task.spawn(function()
		local ok, err = pcall(fn)
		if not ok then warn("[Gonarch] attack error: " .. tostring(err)) end
		for n in pairs(ovr) do ovr[n] = nil end
		resetTargets()
		ATTACK = false
	end)
end

local stabN = 0
local function Stab()
	runAttack(function()
		faceCamera()
		local lg = LEG[(stabN % 2 == 0) and "FL" or "FR"]
		stabN = stabN + 1
		local fwd = fwdVec()
		local R0 = CF(pos) * ANGLES(0, yaw, 0)
		local hip = R0:PointToWorldSpace(lg.p2)
		-- wind-up: raise the leg high over the body
		ovr[lg.n] = { pos = hip + fwd * 3 + V(0, (lg.a + lg.b) * 0.9, 0), k = 12 }
		setT({ bodyX = 0.14, headX = 0.15 })
		task.wait(0.4)
		-- strike: drive the foot into the ground in front
		local tp = pos + fwd * 17
		ovr[lg.n] = { pos = V(tp.X, groundAt(tp, pos.Y) + 0.2, tp.Z), k = 34 }
		setT({ bodyX = -0.2, headX = -0.25 })
		task.wait(0.22)
		TGT.shake = 0.6
		task.wait(0.35)
	end)
end

local function Slam()
	runAttack(function()
		faceCamera()
		local fwd = fwdVec()
		local R0 = CF(pos) * ANGLES(0, yaw, 0)
		for _, n in ipairs({ "FL", "FR" }) do
			local lg = LEG[n]
			ovr[n] = { pos = R0:PointToWorldSpace(lg.p2) + fwd * 2 + V(0, (lg.a + lg.b) * 0.9, 0), k = 9 }
		end
		setT({ bodyX = 0.45, headX = 0.5, drop = -1 })
		task.wait(0.8)
		for _, n in ipairs({ "FL", "FR" }) do
			local lg = LEG[n]
			local tp = R0:PointToWorldSpace(lg.foot) + fwd * 7
			ovr[n] = { pos = V(tp.X, groundAt(tp, pos.Y) + 0.2, tp.Z), k = 40 }
		end
		setT({ bodyX = -0.22, headX = -0.2, drop = 0 })
		task.wait(0.25)
		TGT.shake = 1
		task.wait(0.8)
	end)
end

local function Roar()
	runAttack(function()
		setT({ bodyX = 0.3, headX = 0.65, drop = -0.5 })
		task.wait(0.5)
		TGT.shake = 1
		for _ = 1, 14 do
			TGT.headY = (math.random() - 0.5) * 0.5
			task.wait(0.12)
		end
		TGT.shake = 0
		task.wait(0.2)
	end)
end

local function Charge()
	charging = not charging
	say(charging and "charge gait ON (Z to stop)" or "charge gait off")
end

track(UIS.InputBegan:Connect(function(input, gp)
	if gp or not alive then return end
	local k = input.KeyCode
	if input.UserInputType == Enum.UserInputType.MouseButton1 then Stab()
	elseif k == Enum.KeyCode.Z then Charge()
	elseif k == Enum.KeyCode.T then Roar()
