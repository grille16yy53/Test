local function frame(dt)
	dt = math.min(dt, 0.1)
	clockT = clockT + dt
	local cam = Workspace.CurrentCamera

	-- ===== actions =====
	for k in pairs(ACT) do
		if actions[k] then actions[k] = nil startAct(k) end
	end
	if forced and clockT > forced.untilT then forced = nil end

	local md = RealHum.MoveDirection
	local mag = md.Magnitude
	local running = runToggle or UIS:IsKeyDown(Enum.KeyCode.LeftShift)

	local clipName
	if act then
		act.t = act.t + dt
		cur.t = act.t
		clipName = act.clip
	else
		-- turn towards the move direction, walk/run, idle when still
		local want = 0
		if mag > 0.1 then
			local ty = math.atan2(-md.X, -md.Z)
			local diff = wrap(ty - yaw)
			yaw = yaw + math.clamp(diff, -CFG.TURN_RATE * dt, CFG.TURN_RATE * dt)
			want = (running and CFG.RUN_SPEED or CFG.WALK_SPEED) * math.min(1, mag * 1.2) * math.max(0, 1 - math.abs(diff) / 1.6)
		end
		spd = spd + (want - spd) * math.min(1, dt * CFG.ACCEL)
		if spd < 0.4 then spd = 0 end
		if spd > 0 then moveWithWalls(V(-math.sin(yaw), 0, -math.cos(yaw)) * spd * dt) end
		if spd <= 0.5 then clipName = "idle"
		elseif spd > CFG.WALK_SPEED * 1.35 then clipName = "run"
		else clipName = "walk" end
		if forced and spd <= 0.5 then clipName = forced.name end
		setClip(clipName)
		local c = CLIPS[clipName]
		local rate = 1
		if c.stride > 0 then rate = spd > 0.5 and math.clamp(spd / (c.stride * U), 0.4, 3) or 1 end
		cur.t = cur.t + dt * rate
	end

	-- ===== pose =====
	local c = CLIPS[cur.name]
	samplePose(c, cur.t, pose)
	if act then
		local d = pose.rm - act.prevRm
		act.prevRm = pose.rm
		moveWithWalls(CFrame.Angles(0, yaw, 0):VectorToWorldSpace(d))
		if act.t >= act.dur then act = nil setClip(running and "walk" or "idle") end
	end
	local outRot, outHip = pose.rot, pose.hip
	if fade.k < 1 then
		fade.k = math.min(1, fade.k + dt / CFG.FADE)
		local k = fade.k * fade.k * (3 - 2 * fade.k)
		for i = 1, NB do last.rot[i] = fade.from[i]:Lerp(pose.rot[i], k) end
		last.hip = (fade.fromHip or pose.hip):Lerp(pose.hip, k)
	else
		for i = 1, NB do last.rot[i] = pose.rot[i] end
		last.hip = pose.hip
	end
	outRot, outHip = last.rot, last.hip

	-- ground follow
	local gy = groundBelow(pos + V(0, 8, 0))
	if gy then pos = V(pos.X, pos.Y + (gy - pos.Y) * math.min(1, dt * 14), pos.Z) end

	-- ===== forward kinematics =====
	local root = CF(pos) * CFrame.Angles(0, yaw, 0)
	local W = {}
	for i = 1, NB do
		local p = PARI[i]
		local F
		if p then F = Fr[p] * CF(OFF[i]) * outRot[i]
		else F = root * CF(PIV[i] + outHip) * outRot[i] end
		Fr[i] = F
		W[BONE_ORDER[i]] = F * CF(-PIV[i])
	end

	-- ===== push bone drivers (welded plates follow their driver on the server) =====
	moveAcc = moveAcc + dt
	if moveAcc >= 1 / CFG.UPDATE_HZ then
		moveAcc = 0
		local cnt = 0
		for _, bn in ipairs(BONE_ORDER) do
			local list = byBone[bn]
			local Wb = W[bn]
			if list and Wb then
				for i = 1, #list do
					local f = list[i]
					local cf = Wb * f.cf
					cnt = cnt + 1
					bulkParts[cnt], bulkCFs[cnt] = f.part, cf
					f.bp.Position = cf.Position
					f.bg.CFrame = cf
				end
			end
		end
		for i = cnt + 1, lastN do bulkParts[i], bulkCFs[i] = nil, nil end
		lastN = cnt
		if cnt > 0 then
			local ok = pcall(Workspace.BulkMoveTo, Workspace, bulkParts, bulkCFs, Enum.BulkMoveMode.FireCFrameChanged)
			if not ok then
				local left = pruneDead()
				lastN = 0
				if left < count * 0.5 then shutdown("the plane was despawned") return end
			end
		end
	end

	-- ===== camera target + keep the real character hidden INSIDE the body =====
	camPart.CFrame = CF(pos + V(0, CFG.CAM_HEIGHT, 0))
	RealRoot.Anchored = true
	RealRoot.CFrame = Fr[BIDX.chest] or root
	RealRoot.AssemblyLinearVelocity = ZERO
	hideT = hideT + dt
	if hideT > 0.25 then
		hideT = 0
		for _, d in ipairs(Character:GetDescendants()) do
			if d:IsA("BasePart") then
				d.CanCollide = false
				if CFG.HIDE_SELF then d.LocalTransparencyModifier = 1 end
			end
		end
	end
	fastCam = fastCam + dt
	if fastCam > 1 then
		fastCam = 0
		rayParams.FilterDescendantsInstances = listExclude()
		if cam.CameraSubject ~= camPart then cam.CameraSubject = camPart end
	end
end

