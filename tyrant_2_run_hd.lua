local ALPHA = "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/"
local MAP = {}
for i = 1, 64 do MAP[ALPHA:byte(i)] = i - 1 end
local function decodeClip(c)
	local s, p = c.data, 1
	local function rd(n)
		local v = 0
		for _ = 1, n do v = v * 64 + MAP[s:byte(p)] p = p + 1 end
		return v
	end
	c.f = {}
	for f = 1, c.n do
		local hx, hy, hz = (rd(3) - 131072) * 0.002 * U, (rd(3) - 131072) * 0.002 * U, (rd(3) - 131072) * 0.002 * U
		local rx, rz = (rd(3) - 131072) * 0.001 * U, (rd(3) - 131072) * 0.001 * U
		local rot = {}
		for i = 1, NB do
			local v = rd(6)
			local m = math.floor(v / 1073741824)
			local cs = {
				(math.floor(v / 1048576) % 1024) / 1023 * 1.4144 - 0.7072,
				(math.floor(v / 1024) % 1024) / 1023 * 1.4144 - 0.7072,
				(v % 1024) / 1023 * 1.4144 - 0.7072,
			}
			local qq, ii = { 0, 0, 0, 0 }, 1
			for t = 1, 4 do
				if t - 1 ~= m then qq[t] = cs[ii] ii = ii + 1 end
			end
			qq[m + 1] = math.sqrt(math.max(0, 1 - (cs[1] ^ 2 + cs[2] ^ 2 + cs[3] ^ 2)))
			rot[i] = CF(0, 0, 0, qq[1], qq[2], qq[3], qq[4])
		end
		c.f[f] = { hip = V(hx, hy, hz), rm = V(rx, 0, rz), rot = rot }
		if f % 3 == 0 then task.wait() end
	end
	c.dur = c.n / c.fps
end
