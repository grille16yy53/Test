local function samplePose(c, t, out)
	local n = c.n
	local x, i0, i1 = t * c.fps, 0, 0
	if c.loop then
		x = x % n
		i0 = math.floor(x)
		i1 = (i0 + 1) % n
	else
		x = math.clamp(x, 0, n - 1)
		i0 = math.floor(x)
		i1 = math.min(i0 + 1, n - 1)
	end
	local a = x - i0
	local f0, f1 = c.f[i0 + 1], c.f[i1 + 1]
	for i = 1, NB do out.rot[i] = f0.rot[i]:Lerp(f1.rot[i], a) end
	out.hip = f0.hip:Lerp(f1.hip, a)
	out.rm = f0.rm:Lerp(f1.rm, a)
end

