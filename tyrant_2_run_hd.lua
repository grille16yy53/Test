local function moveWithWalls(delta)
	if delta.Magnitude < 1e-4 then return end
	local from = pos + V(0, 7, 0)
	local r = Workspace:Raycast(from, unit(delta) * (delta.Magnitude + CFG.BODY_RADIUS), rayParams)
	if r and math.abs(r.Normal.Y) < 0.6 then
		delta = delta - r.Normal * delta:Dot(r.Normal)
		local r2 = Workspace:Raycast(from, unit(delta, ZERO) * (delta.Magnitude + CFG.BODY_RADIUS), rayParams)
		if r2 and math.abs(r2.Normal.Y) < 0.6 then return end
	end
	pos = pos + delta
end

