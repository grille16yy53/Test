local slate -- { form = "A"|"B", code = <value> } or nil (= skip materials)
if SLATE_OVERRIDE then
	slate = SLATE_OVERRIDE
elseif not PROBE_SLATE then
	status("no material code known: painting colours only (set SLATE_OVERRIDE to add slate)")
else
	status("probing how to apply the Slate material...")
	local t = smallParts[1]
	local candidates = { Enum.Material.Slate, "Slate", "slate", "SLATE", "Sl", "sl", "s", "S", 800, "800" }
	local function isSlate() return t.part.Material == Enum.Material.Slate end
	if isSlate() then
		slate = { form = "A", code = "Slate" } -- already slate, nothing to learn; use A with the name
	end
	for _, form in ipairs({ "A", "B" }) do
		if slate then break end
		for _, code in ipairs(candidates) do
			callWithTimeout(function()
				if form == "A" then return paintRemote:InvokeServer(t.model, code)
				else return paintRemote:InvokeServer(t.part, Color3.fromRGB(70, 70, 70), code) end
			end)
			local w = 0
			while w < 0.35 and not isSlate() do task.wait(0.05) w = w + 0.05 end
			if isSlate() then slate = { form = form, code = code } break end
		end
	end
	if slate then
		status(("Slate found: form %s, code %s"):format(slate.form, tostring(slate.code)))
	else
		warn("[Gonarch] could not find how to apply Slate - the figure will be painted without a material. "
			.. "Set SLATE_OVERRIDE at the top of script 1 if you know the remote's material code.")
	end
	task.wait(0.3)
end

