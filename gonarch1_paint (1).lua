		local o, box = objs[i], BOXES[i]
		local want = { box.gx, box.gy, box.gz }
		local ok = o and o[1] and o[2] and o[3]
		if ok then
			for k = 1, 3 do
				if math.abs((tonumber(o[k].Value) or -1) - want[k]) > 0.006 then ok = false break end
			end
		end
		if not ok then bad[#bad + 1] = i end
		if i % 400 == 0 then task.wait() end
	end
	cfgFail = #bad
	status(("Size check %d: %d of %d not applied yet"):format(pass, #bad, count))
	if #bad == 0 then break end
	sendSizes(bad)
end

