-- PAINT (colours, plus the material in the same call when form B)
----------------------------------------------------------------------
local jobs = {}
for i = 1, count do
	local box, target = BOXES[i], smallParts[i]
	jobs[i] = { part = target.part, model = target.model, color = box.color, mat = box.mat and slate or nil }
end
local function paintOne(job)
	if not job.mat and job.part.Color == job.color then return true end
	for _ = 1, MAX_RETRIES do
		local ok, r = callWithTimeout(function()
			pace()
			if job.mat and job.mat.form == "B" then
				return paintRemote:InvokeServer(job.part, job.color, job.mat.code)
			end
			return paintRemote:InvokeServer(job.part, job.color, nil)
		end)
		if ok and r then return true end
		task.wait(RETRY_DELAY)
	end
	return false
end

local painted, failed, nextIndex, batchNo = 0, 0, 1, 0
while nextIndex <= #jobs do
	local n = math.min(PAINT_PER_BATCH, #jobs - nextIndex + 1)
	local finished = 0
	for k = 0, n - 1 do
		local job = jobs[nextIndex + k]
		task.spawn(function()
			if not paintOne(job) then failed = failed + 1 end
			finished = finished + 1
		end)
	end
	while finished < n do task.wait() end
	painted = painted + n
	nextIndex = nextIndex + n
	batchNo = batchNo + 1
	if batchNo % 4 == 0 or painted == #jobs then
		status(("Colours %d/%d (%d failed)"):format(painted, #jobs, failed))
	end
end

-- MATERIAL pass for form A (separate call on the model), batched like the colours
if slate and slate.form == "A" then
	local matJobs = {}
	for _, j in ipairs(jobs) do if j.mat then matJobs[#matJobs + 1] = j end end
	local done, idx = 0, 1
	while idx <= #matJobs do
		local n = math.min(PAINT_PER_BATCH, #matJobs - idx + 1)
		local fin = 0
		for k = 0, n - 1 do
			local j = matJobs[idx + k]
			task.spawn(function()
				callWithTimeout(function() pace() return paintRemote:InvokeServer(j.model, slate.code) end)
				fin = fin + 1
			end)
		end
		while fin < n do task.wait() end
		idx = idx + n
		done = done + n
		status(("Material %d/%d"):format(done, #matJobs))
	end
end

