local bucketT = os.clock()
local function pace()
	local now = os.clock()
	bucketT = math.max(bucketT, now - 0.1) + 1 / CALLS_PER_SEC
	if bucketT > now then task.wait(bucketT - now) end
end

local function callWithTimeout(fn)
	local done, ok, res = false, false, nil
	task.spawn(function() ok, res = pcall(fn) done = true end)
	local t = tick()
	while not done and tick() - t < CALL_TIMEOUT do task.wait() end
	if not done then return false end
	return ok, res
end

