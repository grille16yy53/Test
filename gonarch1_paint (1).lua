local function cfgOf(model)
	local c = model:FindFirstChild("Configuration") or model:WaitForChild("Configuration", 3)
	if not c then return nil end
	return c:FindFirstChild("Size X") or c:WaitForChild("Size X", 3), c:FindFirstChild("Size Y") or c:WaitForChild("Size Y", 3), c:FindFirstChild("Size Z") or c:WaitForChild("Size Z", 3)
end

local objs = {}
local function sendSizes(list)
	local sent = 0
	for idx, i in ipairs(list) do
		local box = BOXES[i]
		local o = objs[i]
		if o then
			local v = { box.gx, box.gy, box.gz }
			for k = 1, 3 do
				if o[k] and math.abs((tonumber(o[k].Value) or -1) - v[k]) > 0.006 then
					pace()
					pcall(function() UpdateValue:FireServer(v[k], o[k]) end)
				end
			end
		end
		sent = sent + 1
		if idx % SIZE_PARTS_PER_FRAME == 0 then
			task.wait()
			if idx % (SIZE_PARTS_PER_FRAME * 20) == 0 then status(("Sizes sent %d/%d"):format(idx, #list)) end
		end
	end
end

status("Reading size configs...")
